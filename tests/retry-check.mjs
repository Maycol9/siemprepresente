import { chromium } from 'playwright';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage();
await page.goto(process.env.GAME_URL||'http://127.0.0.1:5173/siemprepresente/',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(1000);
await page.getByRole('button',{name:'Comenzar →',exact:true}).click();
await page.getByRole('button',{name:'Saltar introducción'}).click();
await page.waitForTimeout(500);
await page.keyboard.down('d');await page.waitForTimeout(6900);await page.keyboard.up('d');
await page.getByRole('button',{name:'Reintentar este encuentro'}).waitFor({timeout:50000});
console.log('Daño, invulnerabilidad y derrota: OK');
await page.getByRole('button',{name:'Reintentar este encuentro'}).click();
await page.waitForTimeout(500);
await page.getByRole('button',{name:'Ⅱ Pausa'}).click();
const before=await page.locator('#life').getAttribute('value');
await page.waitForTimeout(1800);
if(before!==await page.locator('#life').getAttribute('value'))throw Error('Daño durante la pausa');
await page.getByRole('button',{name:'Continuar',exact:true}).click();
await page.keyboard.down('d');await page.waitForTimeout(1800);await page.keyboard.up('d');
await page.getByRole('button',{name:'Continuar en modo tranquilo'}).waitFor({timeout:50000});
await page.getByRole('button',{name:'Continuar en modo tranquilo'}).click();
await page.waitForTimeout(500);
await page.getByRole('button',{name:'Ⅱ Pausa'}).click();
await page.getByRole('button',{name:'Modo tranquilo: sí'}).waitFor();
console.log('Reintento, pausa y oferta de modo tranquilo: OK');
await browser.close();
